"""Stage A (run in the upstream mcp venv): build each arm's tools and record what the SDK emits.

For every arm we write a real Python module (arms/<arm>.py) with 18 plain `def`s, register
them on an `MCPServer` with `mcp.tool()`, and call `tools/list` through the in-memory
`Client`. The JSON the client receives is saved verbatim to emitted/<arm>.json. Nothing
here edits the SDK: the emitted text is exactly what main produces today.

Arms
  google, numpy, rest, plain   same information, four markups, raw docstring (main today)
  summary_only                 docstring = summary line only (no parameter info anywhere)
  parsed                       what a docstring parser would emit: description = text sections,
                               parameter docs moved into the schema via Field(description=...).
                               Built from griffe's parse of the google docstrings.

Also writes griffe_parse.json: for each markup, whether griffe (2.1.0, auto-detect and
explicit parser) recovers every parameter description exactly.

Usage (from findings/task1):  uv run --project ../../upstream python gen_arms.py
"""

from __future__ import annotations

import importlib.util
import json
import sys
import textwrap
from pathlib import Path

import anyio

from mcp.client import Client
from mcp.server.mcpserver import MCPServer
from spec import TOOLS, ToolSpec

HERE = Path(__file__).parent
ARMS_DIR = HERE / "arms"
OUT_DIR = HERE / "emitted"


def _sig(t: ToolSpec, annotated: dict[str, str] | None = None) -> str:
    parts = []
    for p in t.params:
        ann = p.type if annotated is None else f"Annotated[{p.type}, Field(description={annotated[p.name]!r})]"
        parts.append(f"{p.name}: {ann}" + (f" = {p.default}" if p.default is not None else ""))
    return ", ".join(parts)


def doc_google(t: ToolSpec) -> str:
    args = "\n".join(f"    {p.name}: {p.desc}" for p in t.params)
    return f"{t.summary}\n\nArgs:\n{args}\n\nReturns:\n    {t.returns}\n"


def doc_numpy(t: ToolSpec) -> str:
    args = "\n".join(
        f"{p.name} : {p.type}{', optional' if p.default is not None else ''}\n    {p.desc}" for p in t.params
    )
    return f"{t.summary}\n\nParameters\n----------\n{args}\n\nReturns\n-------\n{t.returns_type}\n    {t.returns}\n"


def doc_rest(t: ToolSpec) -> str:
    args = "\n".join(f":param {p.name}: {p.desc}\n:type {p.name}: {p.type}" for p in t.params)
    return f"{t.summary}\n\n{args}\n:returns: {t.returns}\n:rtype: {t.returns_type}\n"


def doc_plain(t: ToolSpec) -> str:
    sents = []
    for p in t.params:
        opt = f" (optional, default {p.default})" if p.default is not None else ""
        sents.append(f"The {p.name} argument{opt} gives: {p.desc}")
    return f"{t.summary}\n\n{' '.join(sents)} It returns: {t.returns}\n"


def doc_summary_only(t: ToolSpec) -> str:
    return t.summary


DOCS = {"google": doc_google, "numpy": doc_numpy, "rest": doc_rest, "plain": doc_plain,
        "summary_only": doc_summary_only}


def module_source(arm: str) -> str:
    lines = ["# generated by gen_arms.py - do not edit", "from typing import Annotated", "",
             "from pydantic import Field", "", ""]
    for t in TOOLS:
        if arm == "parsed":
            desc, pdesc = griffe_split(doc_google(t))
            lines.append(f"def {t.name}({_sig(t, pdesc)}) -> {t.returns_type}:")
            lines.append(textwrap.indent(f'"""{desc}"""', "    "))
        else:
            lines.append(f"def {t.name}({_sig(t)}) -> {t.returns_type}:")
            lines.append(textwrap.indent(f'"""{DOCS[arm](t)}"""', "    "))
        lines += ["    raise NotImplementedError", "", ""]
    return "\n".join(lines)


def griffe_split(doc: str, parser: str | None = "google") -> tuple[str, dict[str, str]]:
    """Return (text-section description, {param: description}) as a parser-based PR would."""
    from griffe import Docstring, DocstringSectionKind, Parser, parse, parse_auto

    ds = Docstring(doc, lineno=1)
    sections = parse_auto(ds) if parser is None else parse(ds, Parser(parser))
    text = "\n\n".join(s.value for s in sections if s.kind is DocstringSectionKind.text)
    params: dict[str, str] = {}
    for s in sections:
        if s.kind is DocstringSectionKind.parameters:
            params.update({p.name: p.description for p in s.value})
    return text, params


async def emit(arm: str) -> list[dict]:
    path = ARMS_DIR / f"{arm}.py"
    path.write_text(module_source(arm), encoding="utf-8")
    spec = importlib.util.spec_from_file_location(f"arm_{arm}", path)
    assert spec and spec.loader
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    server = MCPServer(f"arm-{arm}")
    for t in TOOLS:
        server.tool()(getattr(mod, t.name))
    async with Client(server) as client:
        result = await client.list_tools()
    return [tool.model_dump(mode="json", by_alias=True, exclude_none=True) for tool in result.tools]


def griffe_table() -> list[dict]:
    rows = []
    for fmt, parser in [("google", "google"), ("numpy", "numpy"), ("rest", "sphinx"), ("plain", None)]:
        for mode in ("explicit", "auto"):
            if mode == "explicit" and parser is None:
                continue
            ok_tools = ok_params = n_params = 0
            for t in TOOLS:
                doc = DOCS[fmt](t)
                try:
                    text, got = griffe_split(doc, parser if mode == "explicit" else None)
                except Exception as exc:  # record, do not hide
                    got, text = {}, f"<error {type(exc).__name__}: {exc}>"
                exact = sum(got.get(p.name, "").strip() == p.desc for p in t.params)
                ok_params += exact
                n_params += len(t.params)
                ok_tools += exact == len(t.params) and text.strip() == t.summary
            rows.append({"format": fmt, "griffe_mode": mode, "parser": parser,
                         "tools_fully_parsed": ok_tools, "tools": len(TOOLS),
                         "params_exact": ok_params, "params": n_params})
    return rows


async def main() -> None:
    ARMS_DIR.mkdir(exist_ok=True)
    OUT_DIR.mkdir(exist_ok=True)
    for arm in [*DOCS, "parsed"]:
        tools = await emit(arm)
        (OUT_DIR / f"{arm}.json").write_text(json.dumps(tools, indent=2, ensure_ascii=False), encoding="utf-8")
        n_param_desc = sum("description" in p for t in tools for p in t["inputSchema"]["properties"].values())
        print(f"{arm:13s} tools={len(tools)} param_descriptions={n_param_desc} "
              f"mean_desc_chars={sum(len(t.get('description', '')) for t in tools) / len(tools):.0f}")
    rows = griffe_table()
    (HERE / "griffe_parse.json").write_text(json.dumps(rows, indent=2), encoding="utf-8")
    for r in rows:
        print(r)
    print("python", sys.version.split()[0])


if __name__ == "__main__":
    sys.path.insert(0, str(HERE))
    anyio.run(main)
